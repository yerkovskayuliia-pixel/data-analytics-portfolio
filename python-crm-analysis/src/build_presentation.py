prs = Presentation()
prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
BLANK = prs.slide_layouts[6]


def text(slide, x, y, w, h, lines, size=18, color=INK, bold=False):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    for i, line in enumerate(lines if isinstance(lines, list) else [lines]):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = line
        p.font.size, p.font.color.rgb, p.font.bold = Pt(size), color, bold
        p.space_after = Pt(8)
    return box


def slide(title, kicker=None, notes=""):
    s = prs.slides.add_slide(BLANK)
    s.background.fill.solid(); s.background.fill.fore_color.rgb = BG
    if kicker:
        text(s, 0.6, 0.35, 12, 0.4, kicker.upper(), 12, BLUE, True)
    text(s, 0.6, 0.7, 12.1, 1.0, title, 28, INK, True)
    s.notes_slide.notes_text_frame.text = notes
    return s


def kpi(s, x, y, value, label, color=INK):
    text(s, x, y, 2.9, 0.7, value, 32, color, True)
    text(s, x, y + 0.7, 2.9, 0.6, label, 13, INK2)


def image(s, name, x, y, w=None, h=None):
    kw = {}
    if w: kw["width"] = Inches(w)
    if h: kw["height"] = Inches(h)
    s.shapes.add_picture(str(FIG / f"{name}.png"), Inches(x), Inches(y), **kw)


